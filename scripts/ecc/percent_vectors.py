"""Rows of fixtures/ecc/vectors.txt for a scheme that declares a parity percentage (loop 97; contract message-ecc.md 1.1.0).
Called by gen_vectors.py after the rows of the fixed-count schemes; it has its own seeded random stream, so those rows do not move."""
import random

import eccfmt as e

HEADER = """# packbin message ECC vectors for a parity percentage (loop 97). Generated by scripts/ecc/gen_percent_vectors.py, checked by check-vectors.sh.
# Rows are space separated; bytes are hex, "-" is the empty buffer. p = parity percentage, t = correction limit.
# Rows for a scheme that declares a parity percentage p (0 to 100) instead of a count (contract 1.1.0). The count is n(p, L) = min(32, ceil(p * L / 100))
# of the clear length L, and unpack finds L from the sent length alone. p = 0 adds nothing.
#   pct <id> <p> <L> <n>                          the parity count n of a clear message of L bytes under p
#   encp <id> <p> <clear> <protected>             protect under p is exactly <protected>
#   inv <id> <p> <N> <L|none>                     the clear length of a sent length N (p 1 to 100), or none when no message has that length
#   limp <id> <p> <clear_len> <ok|too_long>       protect of <clear_len> zero bytes under p succeeds or is refused (p 1 to 100; p 0 has no limit)
#   fixp <id> <p> <t> <received> <clear> <count>  repair under p with limit t returns <clear>; t above n // 2 of the message is lowered to it
#   badp <id> <p> <t> <received> <kind>           repair under p is refused with <kind> (uncorrectable, too_long)
#   parp <id> <p> <n>                             a scheme that declares percentage p and count n is refused as bad_parity
#   lmtp <id> <t>                                 a limit t below 0 or above 16 under a percentage is refused as bad_limit before any byte is read
"""

POS = bytes.fromhex("4001000065cd1d00a3e1110100")
PCTS = (0, 1, 2, 3, 5, 7, 10, 13, 15, 25, 33, 50, 60, 67, 99, 100)
LENS = (0, 1, 2, 3, 7, 10, 13, 31, 32, 33, 40, 99, 100, 101, 127, 128, 129, 200, 222, 251, 254)
ENC_PCTS = (0, 1, 10, 25, 50, 100)
INV_PCTS = (1, 10, 25, 50, 100)


def hx(b):
    return b.hex() if len(b) else "-"


def corrupt(rng, word, positions):
    w = bytearray(word)
    for p in positions:
        w[p] ^= rng.randint(1, 255)
    return bytes(w)


def refused(received, p, t):
    try:
        e.decode_percent(received, p, t)
    except e.EccError as x:
        return x.kind
    return None


def rows():
    rng = random.Random(97)
    out = []
    msgs = {"pos": POS, "empty": b"", "one": b"\x7f", "ascii": b"packbin ecc 0123456789", "zeros": bytes(40),
            "long": bytes(rng.randrange(256) for _ in range(222))}
    for p in PCTS:
        for ln in LENS:
            out.append("pct pct.p%d.l%d %d %d %d" % (p, ln, p, ln, e.parity_count(p, ln)))
    for name, m in msgs.items():
        for p in ENC_PCTS:
            out.append("encp encp.%s.p%d %d %s %s" % (name, p, p, hx(m), hx(e.protect_percent(m, p))))
    for p in (8, 30, 60):
        out.append("encp encp.pos.p%d %d %s %s" % (p, p, hx(POS), hx(e.protect_percent(POS, p))))
    out.append("inv inv.p0.n0 0 0 0")
    out.append("inv inv.p0.n13 0 13 13")
    out.append("inv inv.p0.n254 0 254 254")
    for p in INV_PCTS:
        for size in list(range(0, 41)) + list(range(215, 255)):
            ln = e.clear_length(p, size)
            out.append("inv inv.p%d.n%d %d %d %s" % (p, size, p, size, "none" if ln is None else ln))
    for p in INV_PCTS:
        top = e.largest_clear(p)
        out.append("limp limp.p%d.%d %d %d ok" % (p, top, p, top))
        out.append("limp limp.p%d.%d %d %d too_long" % (p, top + 1, p, top + 1))
    out.append("limp limp.p0.255 0 255 ok")
    out.append("limp limp.p0.1000 0 1000 ok")
    for p in (10, 25, 50, 100):
        for name in ("pos", "ascii", "zeros"):
            m = msgs[name]
            prot = e.protect_percent(m, p)
            n = len(prot) - len(m)
            tops = sorted({n // 2, 16})
            for t in tops:
                eff = min(t, n // 2)
                for k in sorted({1, eff}):
                    for rep in range(2):
                        pos = rng.sample(range(len(prot)), k)
                        out.append("fixp fixp.%s.p%d.t%d.k%d.%d %d %d %s %s %d" % (name, p, t, k, rep, p, t, hx(corrupt(rng, prot, pos)), hx(m), k))
                out.append("fixp fixp.%s.p%d.t%d.intact %d %d %s %s 0" % (name, p, t, p, t, hx(prot), hx(m)))
            for t in sorted({0, n // 4, n // 2}):
                for k in sorted({t + 1, min(n, t + 3), n}):
                    if k <= t or k > n:
                        continue
                    pos = rng.sample(range(len(prot)), k)
                    bad = corrupt(rng, prot, pos)
                    if refused(bad, p, t) == "uncorrectable":
                        out.append("badp badp.%s.p%d.t%d.k%d %d %d %s uncorrectable" % (name, p, t, k, p, t, hx(bad)))
    out.append("fixp fixp.p0.pos 0 0 %s %s 0" % (hx(POS), hx(POS)))
    out.append("fixp fixp.empty.p25 25 0 - - 0")
    out.append("fixp fixp.empty.p100.t16 100 16 - - 0")
    for p, size in ((100, 1), (100, 3), (100, 7), (100, 63), (25, 1), (25, 6), (25, 11), (10, 23), (1, 1), (1, 102), (10, 254)):
        assert e.clear_length(p, size) is None
        out.append("badp badp.nolen.p%d.n%d %d 0 %s uncorrectable" % (p, size, p, hx(bytes(rng.randrange(256) for _ in range(size)))))
    for p in (25, 100):
        prot = e.protect_percent(msgs["ascii"], p)
        for cut in (1, 2, 3):
            out.append("badp badp.trunc.p%d.%d %d 0 %s uncorrectable" % (p, cut, p, hx(prot[:-cut])))
            ext = prot + bytes(rng.randrange(256) for _ in range(cut))
            assert refused(ext, p, 0) == "uncorrectable"
            out.append("badp badp.extend.p%d.%d %d 0 %s uncorrectable" % (p, cut, p, hx(ext)))
    for p in (1, 25, 100):
        out.append("badp badp.toolong.p%d %d 8 %s too_long" % (p, p, hx(bytes(255))))
    for p, n in ((101, 0), (-1, 0), (255, 0), (20, 4), (1, 1), (100, 32)):
        out.append("parp parp.p%d.n%d %d %d" % (p, n, p, n))
    for t in (-1, 17, 100):
        out.append("lmtp lmtp.t%d %d" % (t, t))
    return out
