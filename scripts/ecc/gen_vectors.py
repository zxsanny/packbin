"""Writes fixtures/ecc/vectors.txt with the reference codec (AZ-2679). Usage: gen_vectors.py [out]"""
import os
import random
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import eccfmt as e  # noqa: E402

POS = bytes.fromhex("4001000065cd1d00a3e1110100")
HEADER = """# packbin message ECC vectors (AZ-2679). Generated by scripts/ecc/gen_vectors.py, checked by check-vectors.sh.
# Rows are space separated; bytes are hex, "-" is the empty buffer. n = parity bytes, t = correction limit.
#   enc <id> <n> <clear> <protected>              protect(clear, n) is exactly <protected>; <protected> is <clear> then n parity bytes
#   fix <id> <n> <t> <received> <clear> <count>   repair(received, n, t) returns <clear> and reports <count> repaired bytes
#   bad <id> <n> <t> <received> <kind>            repair(received, n, t) is refused with <kind> (uncorrectable, short, too_long)
#                                                 a buffer above 254 bytes is too_long; protect of a clear message above 254 - n bytes is too_long
#   lim <id> <n> <clear_len> <ok|too_long>        protect of <clear_len> zero bytes under n parity bytes succeeds or is refused
#   par <id> <n>                                  a scheme that declares n parity bytes is refused as bad_parity
#   lmt <id> <n> <t>                              repair with limit t above n // 2 is refused as bad_limit before any byte is read
# Code: GF(256), field polynomial 0x11D, alpha = 2, generator roots alpha^0 .. alpha^(n-1), parity after the clear bytes.
# The code word is one byte longer than what is sent: the clear length is its first byte and is not sent (message-ecc.md).
"""


def hx(b):
    return b.hex() if len(b) else "-"


def corrupt(rng, word, positions):
    w = bytearray(word)
    for p in positions:
        w[p] ^= rng.randint(1, 255)
    return bytes(w)


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "..", "..", "fixtures", "ecc", "vectors.txt")
    rng = random.Random(38)
    rows = []
    msgs = {"pos": POS, "empty": b"", "one": b"\x7f", "ascii": b"packbin ecc 0123456789", "zeros": bytes(40)}
    msgs["long"] = bytes(rng.randrange(256) for _ in range(222))
    for name, m in msgs.items():
        for n in (0, 1, 2, 4, 8, 16, 32):
            if len(m) <= 255 - n:
                rows.append("enc enc.%s.n%d %d %s %s" % (name, n, n, hx(m), hx(e.protect(m, n))))
    # results report rows 7, 8, 11
    p2, p4 = e.protect(POS, 2), e.protect(POS, 4)
    c = bytearray(p2); c[5] ^= 0x01
    rows.append("fix fix.report.r7 2 1 %s %s 1" % (hx(bytes(c)), hx(POS)))
    c = bytearray(p4); c[2] ^= 0x5A; c[9] ^= 0xC3
    two = bytes(c)
    rows.append("fix fix.report.r8 4 2 %s %s 2" % (hx(two), hx(POS)))
    rows.append("bad bad.report.r9 4 1 %s uncorrectable" % hx(two))
    rows.append("bad bad.report.r10 4 0 %s uncorrectable" % hx(two))
    rows.append("fix fix.report.r11 4 2 %s %s 0" % (hx(p4), hx(POS)))
    rows.append("bad bad.report.r12 4 2 400100 short")
    rows.append("bad bad.report.short0 1 0 - short")
    # seeded repairs and refusals for every n
    for n in (2, 4, 8, 16, 32):
        for name in ("pos", "ascii", "long"):
            m = msgs[name]
            prot = e.protect(m, n)
            for t in sorted({n // 2, max(1, n // 4)}):
                for k in sorted({1, t}):
                    for rep in range(2):
                        pos = rng.sample(range(len(prot)), k)
                        r = corrupt(rng, prot, pos)
                        rows.append("fix fix.%s.n%d.t%d.k%d.%d %d %d %s %s %d" % (name, n, t, k, rep, n, t, hx(r), hx(m), k))
            # first byte, last byte, parity-only damage at full capacity
            t = n // 2
            for label, pos in (("first", [0]), ("last", [len(prot) - 1]), ("parity", list(range(len(prot) - t, len(prot))))):
                rows.append("fix fix.%s.n%d.%s %d %d %s %s %d" % (name, n, label, n, t, hx(corrupt(rng, prot, pos)), hx(m), len(pos)))
            # refusals: t+1 .. n-t wrong bytes are never repaired and never a wrong row
            for t in range(0, n // 2 + 1):
                for k in range(t + 1, n - t + 1):
                    pos = rng.sample(range(len(prot)), k)
                    rows.append("bad bad.%s.n%d.t%d.k%d %d %d %s uncorrectable" % (name, n, t, k, n, t, hx(corrupt(rng, prot, pos))))
    # truncation and extension of a protected message, detect only
    p4 = e.protect(POS, 4)
    for cut in (1, 2, 3):
        rows.append("bad bad.trunc.%d 4 0 %s uncorrectable" % (cut, hx(p4[:-cut])))
        rows.append("bad bad.extend.%d 4 0 %s uncorrectable" % (cut, hx(p4 + bytes(rng.randrange(256) for _ in range(cut)))))
    rows.append("bad bad.unprotected 4 0 %s uncorrectable" % hx(POS))
    # limits
    for n, ln, want in ((4, 250, "ok"), (4, 251, "too_long"), (32, 222, "ok"), (32, 223, "too_long"), (1, 253, "ok"), (1, 254, "too_long"), (0, 255, "ok")):
        rows.append("lim lim.n%d.%d %d %d %s" % (n, ln, n, ln, want))
    rows.append("bad bad.toolong.n4 4 2 %s too_long" % hx(bytes(255)))
    for n in (33, 64, 255):
        rows.append("par par.n%d %d" % (n, n))
    for n, t in ((0, 1), (2, 2), (4, 3), (32, 17)):
        rows.append("lmt lmt.n%d.t%d %d %d" % (n, t, n, t))
    with open(out, "w") as f:
        f.write(HEADER + "\n".join(rows) + "\n")
    print("wrote %d rows to %s" % (len(rows), out))


if __name__ == "__main__":
    main()
