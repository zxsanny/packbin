"""Writes fixtures/ecc/ring-cases.txt with the reference codec (AZ-2689). Usage: gen_ring_cases.py [out]

The rows the cross-language ring (.github/workflows/ring-ecc.sh) adds to the position rows of vectors.txt: seeded
repairs and refusals of the position message, and the refusals of a hostile buffer (a message cut short, one with
bytes added, an unprotected one, garbage, a buffer past 254 bytes, a protected message read by a scheme without
parity). Row syntax is that of vectors.txt for `fix` and `bad`; every clear message is a position message (type 0x40,
13 bytes) so the ring drivers can read it with the position scheme. Seeded, so a rerun gives the same file.
"""
import os
import random
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import eccfmt as e  # noqa: E402

POS = bytes.fromhex("4001000065cd1d00a3e1110100")
HEADER = """# packbin message ECC ring cases (AZ-2689). Generated by scripts/ecc/gen_ring_cases.py, run by .github/workflows/ring-ecc.sh.
# Same syntax as vectors.txt, `fix` and `bad` rows only. Every clear message is a position message (type 0x40, 13 bytes):
#   fix <id> <n> <t> <received> <clear> <count>   a scheme with n parity bytes reads <received> with limit t and gives <clear>, <count> bytes repaired
#   enc <id> <n> <clear> <protected>              a scheme with n parity bytes writes <protected> for the position message
#   par <id> <n>                                  a scheme that declares n is refused as bad_parity
#   lmt <id> <n> <t>                              a limit t outside what n allows is refused as bad_limit, before any byte is read
#   bad <id> <n> <t> <received> <kind>            it refuses <received> as <kind>: uncorrectable, short, too_long, or trailing
#                                                 (trailing: n = 0, the scheme has no parity bytes and the message is longer than its fields)
# Where a row has <n>, `p<N>` (p25: 25 percent) is a scheme that declares a parity percentage instead of a count (contract 1.1.0):
# the count is the percentage of the clear length, rounded up, at most 32; the limit t is 0 to 16 and is lowered to n / 2.
# The ring checks each row against the reference codec (scripts/ecc/eccfmt.py) and against every package that reads it.
# Rows whose id starts with ring.hostile. are the refusals of EC-14 and EC-4: truncation, extension, unprotected bytes,
# garbage, an oversize buffer. None of them may give a row.
"""


def hx(b):
    return b.hex() if len(b) else "-"


def position(sid, lat, lon, profile):
    return bytes([0x40]) + struct.pack("<HiiB", sid, lat, lon, profile) + b"\x00"


def corrupt(rng, word, count, include=None):
    pos = [include] if include is not None else []
    while len(pos) < count:
        p = rng.randrange(len(word))
        if p not in pos:
            pos.append(p)
    w = bytearray(word)
    for p in pos:
        w[p] ^= rng.randint(1, 255)
    return bytes(w)


def refusal(word, n, t):
    try:
        decode(word, n, t)
    except e.EccError as x:
        return x.kind
    return None


def decode(word, n, t):
    """n is a count or `p<N>` (a percentage)."""
    return e.decode_percent(word, int(n[1:]), t) if isinstance(n, str) else e.decode(word, n, t)


def protect(clear, n):
    return e.protect_percent(clear, int(n[1:])) if isinstance(n, str) else e.protect(clear, n)


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "fixtures", "ecc", "ring-cases.txt")
    rng = random.Random(2689)
    rows = []

    def fix(rid, n, t, word, clear, count):
        got = decode(word, n, t)
        assert got == (clear, count), (rid, got)
        rows.append("fix %s %s %d %s %s %d" % (rid, n, t, hx(word), hx(clear), count))

    def bad(rid, n, t, word, want=None):
        kind = refusal(word, n, t)
        assert kind is not None and want in (None, kind), (rid, kind)
        rows.append("bad %s %s %d %s %s" % (rid, n, t, hx(word), kind))

    # The intact message under every n, detect-only and at the full limit.
    for n in (1, 2, 4, 8, 16, 32):
        for t in sorted({0, n // 2}):
            fix("ring.intact.n%d.t%d" % (n, t), n, t, e.protect(POS, n), POS, 0)
    # n = 2: every position, one wrong byte (EC-5's sweep with one seeded value per position).
    prot = e.protect(POS, 2)
    for p in range(len(prot)):
        word = bytearray(prot)
        word[p] ^= rng.randint(1, 255)
        fix("ring.n2.p%d" % p, 2, 1, bytes(word), POS, 1)
    # n = 1 detects any single wrong byte.
    prot = e.protect(POS, 1)
    for p in range(len(prot)):
        word = bytearray(prot)
        word[p] ^= rng.randint(1, 255)
        bad("ring.n1.p%d" % p, 1, 0, bytes(word), "uncorrectable")
    for n in (2, 4, 8, 16):
        prot = e.protect(POS, n)
        for t in sorted({n // 2, max(1, n // 4)}):
            for k in range(1, t + 1):
                for rep in range(2):
                    fix("ring.fix.n%d.t%d.k%d.%d" % (n, t, k, rep), n, t, corrupt(rng, prot, k), POS, k)
            # The type byte is always among the wrong bytes: the repair comes before the dispatch.
            fix("ring.fix.n%d.t%d.type" % (n, t), n, t, corrupt(rng, prot, t, include=0), POS, t)
            for k in range(t + 1, n - t + 1):
                for rep in range(2):
                    bad("ring.bad.n%d.t%d.k%d.%d" % (n, t, k, rep), n, t, corrupt(rng, prot, k), "uncorrectable")
        for k in sorted({1, n // 2, n}):
            for rep in range(2):
                bad("ring.bad.n%d.t0.k%d.%d" % (n, k, rep), n, 0, corrupt(rng, prot, k), "uncorrectable")
    # Other position messages (the sid, latitude and longitude vary): a repair does not depend on the fixture's bytes.
    for i in range(6):
        msg = position(rng.randrange(65536), rng.randrange(-2**31, 2**31), rng.randrange(-2**31, 2**31), rng.randrange(256))
        n = (2, 4, 8, 16)[i % 4]
        t = n // 2
        word = corrupt(rng, e.protect(msg, n), 1)
        fix("ring.vary.n%d.%d" % (n, i), n, t, word, msg, 1)
    # A message whose last parity byte is 00: a trailing 00 and a dropped last byte each shift the message by one.
    zero = None
    for sid in range(65536):
        cand = position(sid, 500_000_000, 300_000_000, 1)
        if e.protect(cand, 4)[-1] == 0:
            zero = cand
            break
    assert zero is not None
    zp = e.protect(zero, 4)
    fix("ring.hostile.zero.intact", 4, 0, zp, zero, 0)
    bad("ring.hostile.zero.append", 4, 0, zp + b"\x00", "uncorrectable")
    bad("ring.hostile.zero.drop", 4, 0, zp[:-1], "uncorrectable")
    # The fixture with a trailing 00 or its last byte dropped, under every n.
    for n in (2, 4, 8, 16):
        prot = e.protect(POS, n)
        bad("ring.hostile.n%d.append00" % n, n, 0, prot + b"\x00", "uncorrectable")
        bad("ring.hostile.n%d.drop1" % n, n, 0, prot[:-1], "uncorrectable")
        for cut in (2, 3):
            bad("ring.hostile.n%d.trunc%d" % (n, cut), n, 0, prot[:-cut], "uncorrectable")
        for extra in (1, 2, 3):
            for rep in range(2):
                bad("ring.hostile.n%d.extend%d.%d" % (n, extra, rep), n, 0, prot + bytes(rng.randrange(256) for _ in range(extra)), "uncorrectable")
        bad("ring.hostile.n%d.unprotected" % n, n, 0, POS)  # uncorrectable, or short when 13 bytes are fewer than n
        # A protected message read by a scheme with no parity bytes: the bytes after the fields are trailing.
        rows.append("bad ring.hostile.n%d.trailing 0 0 %s trailing" % (n, hx(prot)))
    # Cut below n bytes: the shortage names the parity.
    for n, length in ((4, 0), (4, 1), (4, 3), (8, 7), (16, 15), (16, 0)):
        bad("ring.hostile.short.n%d.len%d" % (n, length), n, n // 2, POS[:length], "short")
    # Garbage of the fixture's length, detect only; and of other lengths.
    for n in (2, 4, 8, 16):
        made = 0
        while made < 12:
            word = bytes(rng.randrange(256) for _ in range(13 + n))
            if refusal(word, n, 0) == "uncorrectable":
                bad("ring.hostile.garbage.n%d.%d" % (n, made), n, 0, word, "uncorrectable")
                made += 1
    for n, length in ((4, 4), (4, 5), (4, 40), (8, 9), (16, 100), (2, 254)):
        while True:
            word = bytes(rng.randrange(256) for _ in range(length))
            if refusal(word, n, 0) == "uncorrectable":
                break
        bad("ring.hostile.garbage.n%d.len%d" % (n, length), n, 0, word, "uncorrectable")
    # A buffer past 254 bytes is refused before it is read.
    for n, length in ((2, 255), (4, 256), (16, 300), (32, 255)):
        bad("ring.hostile.toolong.n%d.len%d" % (n, length), n, n // 2, bytes(rng.randrange(256) for _ in range(length)), "too_long")
    # A parity percentage (contract 1.1.0): the count is found from the received length alone.
    for p in (10, 25, 50, 100):
        s = "p%d" % p
        prot = protect(POS, s)
        n = len(prot) - len(POS)
        rows.append("enc ring.%s.enc %s %s %s" % (s, s, hx(POS), hx(prot)))
        for t in sorted({0, n // 2, 16}):
            fix("ring.%s.intact.t%d" % (s, t), s, t, prot, POS, 0)
        for t in sorted({n // 2, 16}):
            for k in sorted({1, n // 2}):
                if k < 1:
                    continue
                for rep in range(2):
                    fix("ring.%s.fix.t%d.k%d.%d" % (s, t, k, rep), s, t, corrupt(rng, prot, k), POS, k)
        fix("ring.%s.fix.type" % s, s, 16, corrupt(rng, prot, n // 2, include=0), POS, n // 2)
        for t in sorted({0, n // 4, n // 2}):
            for k in sorted({t + 1, min(n, t + 3), n}):
                if k <= t or k > n:
                    continue
                word = corrupt(rng, prot, k)
                if refusal(word, s, t) == "uncorrectable":
                    bad("ring.%s.bad.t%d.k%d" % (s, t, k), s, t, word, "uncorrectable")
        for cut in (1, 2, 3):
            bad("ring.%s.hostile.trunc%d" % (s, cut), s, 0, prot[:-cut], "uncorrectable")
        for extra in (1, 2):
            bad("ring.%s.hostile.extend%d" % (s, extra), s, 0, prot + bytes(rng.randrange(256) for _ in range(extra)), "uncorrectable")
        bad("ring.%s.hostile.unprotected" % s, s, 0, POS, "uncorrectable")
        bad("ring.%s.hostile.toolong" % s, s, 8, bytes(rng.randrange(256) for _ in range(255)), "too_long")
    # A length no clear message has under the percentage, with no parity check passing it.
    for s, length in (("p100", 1), ("p100", 25), ("p100", 27), ("p25", 16), ("p10", 12), ("p10", 23)):
        word = bytes(rng.randrange(256) for _ in range(length))
        bad("ring.%s.hostile.nolen%d" % (s, length), s, 0, word, "uncorrectable")
    for p in (101, 255):
        rows.append("par ring.par.p%d p%d" % (p, p))
    for s, t in (("p25", 17), ("p25", 100), ("p100", 17)):
        rows.append("lmt ring.lmt.%s.t%d %s %d" % (s, t, s, t))
    ids = [r.split(" ")[1] for r in rows]
    assert len(ids) == len(set(ids))
    with open(out, "w") as f:
        f.write(HEADER + "\n".join(rows) + "\n")
    print("wrote %d rows to %s" % (len(rows), out))


if __name__ == "__main__":
    main()
