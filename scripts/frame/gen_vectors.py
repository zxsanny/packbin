#!/usr/bin/env python3
"""Writes fixtures/frame/vectors.txt (or the path given) from a fixed seed with the reference of framefmt.py.
A rerun gives the same file. Python 3.9+, standard library only."""
import hashlib
import hmac
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import coverage as cov  # noqa: E402
import framefmt as ff  # noqa: E402
import rows  # noqa: E402

SEED = b"packbin frame vectors 2026-10-25"
HEADER = """# packbin frame mode vectors (AZ-3202). Generated by scripts/frame/gen_vectors.py, checked by check-vectors.sh.
# Contract: _docs/02_document/contracts/library/pack-session.md 2.0.0 (frame mode, MAC-only). Rows are one per line:
#   op=<keys|seal|open|mac|replay> case=<unique name> <input fields> <output fields>
# Hex fields have no separators and "-" is empty. Integer fields (epoch, dir, tag_len, kind, n, clear_len, out_len,
# counter) are decimal. window is "top:bits" in hex; steps is check:N or commit:N (decimal) joined by commas; parts is
# hex pieces joined by "|". dirs (default 123) names the directions the session loaded. out_len is the caller's buffer.
#   keys  key epoch dir        -> k_enc k_mac        |  key epoch label -> k_label
#   seal  key epoch dir tag_len msg_id kind ad clear plain [dirs out_len] -> body | result=<error kind>
#   open  key epoch [prev_key prev_epoch] dir tag_len msg_id kind ad clear_len body [dirs window counter out_len]
#         -> result=Ok slot=current|previous plain [window_after] | result=<error kind> [window_after = window]
#   mac   key epoch label n (message | parts) -> tag | result=<error kind>;  key epoch label verify=<tag> -> valid
#   replay steps -> results (one per check) states (top:bits after each commit)
# E1 to E5 are the worked examples of the contract, computed by meshbell with an independent implementation.
"""


def det(label, n):
    """n deterministic bytes from the seed and a label (HMAC-SHA256 counter mode)."""
    out, counter = b"", 0
    while len(out) < n:
        out += hmac.new(SEED, label.encode() + bytes([counter]), hashlib.sha256).digest()
        counter += 1
    return out[:n]


def seq(first, count):
    return bytes((first + i) & 0xFF for i in range(count))


class Builder:
    def __init__(self):
        self.lines, self.names = [], set()

    def add(self, op, case, **fields):
        assert case not in self.names, case
        self.names.add(case)
        row = {"op": op, "case": case}
        row.update(fields)
        row.update(rows.run(row))
        self.lines.append(rows.render(row))
        return row


def seal_fields(key, epoch, d, tag_len, msg_id, kind, ad, clear, plain, **extra):
    fields = dict(key=rows.hx(key), epoch=str(epoch), dir=str(d), tag_len=str(tag_len), msg_id=rows.hx(msg_id),
                  kind=str(kind), ad=rows.hx(ad), clear=rows.hx(clear), plain=rows.hx(plain))
    fields.update({k: str(v) for k, v in extra.items()})
    return fields


def open_fields(sealed, body, **extra):
    fields = dict(key=sealed["key"], epoch=sealed["epoch"], dir=sealed["dir"], tag_len=sealed["tag_len"],
                  msg_id=sealed["msg_id"], kind=sealed["kind"], ad=sealed["ad"],
                  clear_len=str(len(rows.unhex(sealed["clear"]))), body=body)
    fields.update({k: str(v) for k, v in extra.items()})
    return fields


def flip(data, index):
    out = bytearray(data)
    out[index] ^= 1
    return bytes(out)


def build():
    b = Builder()
    examples = {}
    spec = {
        "E1": (bytes([0x11]) * 32, 1, 1, 4, bytes.fromhex("00301005e8030000"), 4,
               bytes.fromhex("000100301005e803000004"), b"", bytes.fromhex("0102030405060708090a0b0c")),
        "E2": (bytes([0x11]) * 32, 1, 2, 4, bytes.fromhex("00022001e9030000"), 5,
               bytes.fromhex("003000022001e903000005"), b"", seq(0x40, 42)),
        "E3": (bytes([0x33]) * 32, 7, 3, 4, bytes.fromhex("00013002ea030000"), 6,
               bytes.fromhex("ffff00013002ea03000006"), bytes.fromhex("a1b2c3"), seq(0x80, 20)),
    }
    for name, args in spec.items():
        key, epoch, d = args[0], args[1], args[2]
        b.add("keys", name + ".keys", key=rows.hx(key), epoch=str(epoch), dir=str(d))
        sealed = b.add("seal", name + ".seal", **seal_fields(*args))
        examples[name] = (sealed, sealed["body"])
        b.add("open", name + ".open", **open_fields(sealed, sealed["body"]))
    sealed16 = b.add("seal", "E3.seal16", **seal_fields(*spec["E3"][:3], 16, *spec["E3"][4:]))
    b.add("open", "E3.open16", **open_fields(sealed16, sealed16["body"]))
    k22 = bytes([0x22]) * 32
    wave_message = bytes.fromhex("e8030000") + seq(0xC0, 20)
    b.add("keys", "E4.keys", key=rows.hx(k22), epoch="7", label=rows.hx(b"net"))
    b.add("mac", "E4.mac", key=rows.hx(k22), epoch="7", label=rows.hx(b"net"), n="4", message=rows.hx(wave_message))
    b.add("keys", "E5.keys", key=rows.hx(k22), epoch="8", label=rows.hx(b"net"))
    b.add("mac", "E5.mac", key=rows.hx(k22), epoch="8", label=rows.hx(b"net"), n="4", message=rows.hx(b"check"))

    kkeys = det("keys", 32)
    for d in (1, 2, 3):
        for e in cov.EPOCHS:
            b.add("keys", "keys.d%d.e%x" % (d, e), key=rows.hx(kkeys), epoch=str(e), dir=str(d))

    base = dict(key=det("refuse", 32), epoch=3, d=1, tag_len=4, msg_id=det("refuse.id", 8), kind=2, ad=det("a", 11),
                clear=b"", plain=det("p", 12))

    def refuse(name, **change):
        args = dict(base)
        extra = {k: change.pop(k) for k in ("dirs", "out_len") if k in change}
        args.update(change)
        b.add("seal", "refuse.seal." + name, **seal_fields(args["key"], args["epoch"], args["d"], args["tag_len"],
                                                          args["msg_id"], args["kind"], args["ad"], args["clear"],
                                                          args["plain"], **extra))

    refuse("epoch1000000", epoch=0x1000000)
    refuse("dir0", d=0)
    refuse("dir4", d=4)
    refuse("kind16", kind=16)
    refuse("unloaded", d=2, dirs="1")
    refuse("tag0", tag_len=0)
    refuse("tag5", tag_len=5)
    refuse("tag32", tag_len=32)
    refuse("ad256", ad=det("ad256", 256))
    refuse("body256", plain=det("b256", 252))
    refuse("outshort", out_len=15)
    opened = b.add("seal", "refuse.open.base", **seal_fields(base["key"], 3, 1, 4, base["msg_id"], 2, base["ad"],
                                                             b"", base["plain"]))
    b.lines.pop()
    b.names.discard("refuse.open.base")
    body = opened["body"]
    b.add("open", "refuse.open.kind16", **open_fields(opened, body, kind=16))
    b.add("open", "refuse.open.unloaded", **open_fields(opened, body, dirs="2"))
    b.add("open", "refuse.open.ad256", **open_fields(opened, body, ad=rows.hx(det("ad256", 256))))
    b.add("open", "refuse.open.short", **open_fields(opened, rows.hx(rows.unhex(body)[:3])))
    b.add("open", "refuse.open.buffer", **open_fields(opened, body, out_len=11))

    lkey, lid, lad = det("len", 32), det("len.id", 8), det("len.ad", 255)
    for n in cov.PLAIN_LENS:
        b.add("seal", "len.plain%d" % n, **seal_fields(lkey, 5, 1, 4, lid, 3, lad[:11], b"", det("plain%d" % n, n)))
    for n in cov.CLEAR_LENS:
        b.add("seal", "len.clear%d" % n, **seal_fields(lkey, 5, 2, 4, lid, 3, lad[:11], det("clear%d" % n, n),
                                                       det("plain12", 12)))
    for n in cov.AD_LENS:
        b.add("seal", "len.ad%d" % n, **seal_fields(lkey, 5, 3, 4, lid, 3, lad[:n], det("clear3", 3), det("plain12", 12)))
    for t in cov.TAG_LENS:
        b.add("seal", "tag.t%d" % t, **seal_fields(lkey, 5, 1, t, lid, 3, lad[:11], det("clear3", 3), det("plain12", 12)))

    for name, (sealed, body) in examples.items():
        raw = rows.unhex(body)
        clear = rows.unhex(sealed["clear"])
        plain_len = len(raw) - len(clear) - 4
        ad = rows.unhex(sealed["ad"])
        key = rows.unhex(sealed["key"])
        msg_id = rows.unhex(sealed["msg_id"])
        kind, epoch, d = int(sealed["kind"]), int(sealed["epoch"]), int(sealed["dir"])
        other_dir = {1: 2, 2: 3, 3: 1}[d]
        change = {
            "ad_first": dict(ad=rows.hx(flip(ad, 0))), "ad_last": dict(ad=rows.hx(flip(ad, len(ad) - 1))),
            "ct_first": dict(body=rows.hx(flip(raw, len(clear)))),
            "ct_last": dict(body=rows.hx(flip(raw, len(clear) + plain_len - 1))),
            "tag_first": dict(body=rows.hx(flip(raw, len(raw) - 4))),
            "tag_last": dict(body=rows.hx(flip(raw, len(raw) - 1))),
            "msgid": dict(msg_id=rows.hx(flip(msg_id, 0))), "kind": dict(kind=str(kind ^ 1)),
            "dir": dict(dir=str(other_dir)), "epoch": dict(epoch=str(epoch + 1)),
            "key": dict(key=rows.hx(flip(key, 0))), "clearlen_up": dict(clear_len=str(len(clear) + 1)),
        }
        if name == "E3":
            change.update({"clear_first": dict(body=rows.hx(flip(raw, 0))),
                           "clear_last": dict(body=rows.hx(flip(raw, len(clear) - 1))),
                           "clearlen_down": dict(clear_len=str(len(clear) - 1))})
        for variant in cov.TAMPER_ALL + (cov.TAMPER_E3 if name == "E3" else ()):
            fields = open_fields(sealed, body)
            fields.update(change[variant])
            b.add("open", "tamper.%s.%s" % (name, variant), **fields)

    pkey_a, pkey_b = det("prev.A", 32), det("prev.B", 32)
    pid, pad_ = det("prev.id", 8), det("prev.ad", 11)
    plain = det("prev.plain", 20)
    old = b.add("seal", "prev.seal_old", **seal_fields(pkey_a, 6, 2, 4, pid, 5, pad_, b"", plain))
    new = b.add("seal", "prev.seal_new", **seal_fields(pkey_b, 7, 2, 4, pid, 5, pad_, b"", plain))
    for row in (old, new):
        b.lines.pop()
        b.names.discard(row["case"])
    two_slots = dict(key=rows.hx(pkey_b), epoch=7, prev_key=rows.hx(pkey_a), prev_epoch=6)
    base_open = open_fields(dict(new, key=rows.hx(pkey_b), epoch="7"), old["body"])
    base_open.update({k: str(v) for k, v in two_slots.items()})
    b.add("open", "prev.ok_previous", **base_open)
    no_slot = {k: v for k, v in base_open.items() if not k.startswith("prev_")}
    b.add("open", "prev.no_slot", **no_slot)
    cur = dict(base_open, body=new["body"])
    b.add("open", "prev.ok_current", **cur)

    steps = ",".join(cov.REPLAY_SEQUENCE)
    b.add("replay", "replay.seq17", steps=steps)
    b.add("replay", "replay.empty0", steps="check:0,commit:0,check:0")
    top = (1 << 64) - 1
    b.add("replay", "replay.max64", steps="commit:%d,check:0,check:%d,check:%d" % (top, top - 63, top - 64))

    wkey, wid, wad = det("win", 32), det("win.id", 8), det("win.ad", 11)
    wseal = b.add("seal", "openwin.seal", **seal_fields(wkey, 2, 1, 4, wid, 1, wad, b"", det("win.plain", 16)))
    b.lines.pop()
    b.names.discard("openwin.seal")
    wbody = wseal["body"]
    b.add("open", "openwin.duplicate", **open_fields(wseal, wbody, window="64:1", counter=100))
    b.add("open", "openwin.tampered", **open_fields(wseal, rows.hx(flip(rows.unhex(wbody), len(rows.unhex(wbody)) - 1)),
                                                    window="64:1", counter=101))
    b.add("open", "openwin.fresh", **open_fields(wseal, wbody, window="64:1", counter=101))
    b.add("open", "openwin.tooold", **open_fields(wseal, wbody, window="64:1", counter=36))

    mkey = det("mac", 32)
    mbase = dict(key=rows.hx(mkey), epoch="9")
    msg = det("mac.msg", 255)
    b.add("mac", "mac.label1", label=rows.hx(b"x"), n="4", message=rows.hx(msg[:20]), **mbase)
    b.add("mac", "mac.label32", label=rows.hx(det("label32", 32)), n="4", message=rows.hx(msg[:20]), **mbase)
    b.add("mac", "mac.label0", label="-", n="4", message=rows.hx(msg[:20]), **mbase)
    b.add("mac", "mac.label33", label=rows.hx(det("label33", 33)), n="4", message=rows.hx(msg[:20]), **mbase)
    for n in cov.MAC_NS:
        b.add("mac", "mac.n%d" % n, label=rows.hx(b"net"), n=str(n), message=rows.hx(msg[:20]), **mbase)
    for n in cov.BAD_MAC_NS:
        b.add("mac", "mac.nbad%d" % n, label=rows.hx(b"net"), n=str(n), message=rows.hx(msg[:20]), **mbase)
    for n in cov.MSG_LENS:
        data = msg[:n]
        cuts = {1: [], 2: [n // 2], 3: [n // 3, (2 * n) // 3]}
        for parts, points in cuts.items():
            pieces, last = [], 0
            for cut in points + [n]:
                pieces.append(data[last:cut])
                last = cut
            fields = dict(label=rows.hx(b"net"), n="4", **mbase)
            if parts == 1:
                fields["message"] = rows.hx(data)
            else:
                fields["parts"] = "|".join(rows.hx(p) for p in pieces)
            b.add("mac", "mac.len%d.parts%d" % (n, parts), **fields)
    good = ff.mac_tag(mkey, 9, b"net", 4, [msg[:20]])
    b.add("mac", "mac.verify_ok", label=rows.hx(b"net"), message=rows.hx(msg[:20]), verify=rows.hx(good), **mbase)
    b.add("mac", "mac.verify_flip", label=rows.hx(b"net"), message=rows.hx(msg[:20]), verify=rows.hx(flip(good, 3)),
          **mbase)
    return b.lines


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "..", "fixtures", "frame", "vectors.txt")
    text = HEADER + "\n".join(build()) + "\n"
    with open(out, "w", newline="\n") as handle:
        handle.write(text)
    print("wrote %s" % out)


if __name__ == "__main__":
    main()
