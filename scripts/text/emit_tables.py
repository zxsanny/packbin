#!/usr/bin/env python3
"""Emit the compact text constants of fixtures/text/tables.json as source for one language (AZ-2647).

Usage:
  emit_tables.py <lang> > file         lang: python typescript csharp java rust go swift cpp
  emit_tables.py <lang> --check FILE   exit 0 when FILE is exactly the emitted text

Every package keeps the emitted file unedited; a check in its tests or in CI proves it still matches
tables.json. The package builds its canonical codes from the lengths (contract: Code assignment).
"""
import hashlib
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TABLES = os.path.join(HERE, "..", "..", "fixtures", "text", "tables.json")
LANGS = ("python", "typescript", "csharp", "java", "rust", "go", "swift", "cpp")
SUGGESTED = {
    "python": "python/src/packbin/_text_tables.py", "typescript": "typescript/src/text-tables.ts",
    "csharp": "csharp/TextTables.cs", "java": "java/src/main/java/packbin/TextTables.java",
    "rust": "rust/src/walk/text_tables.rs", "go": "go/text_tables.go",
    "swift": "swift/Sources/Packbin/TextTables.swift", "cpp": "cpp/include/packbin/text_tables.hpp",
}
NOTE = "Generated by scripts/text/emit_tables.py from fixtures/text/tables.json. Do not edit."


def load():
    raw = open(TABLES, "rb").read()
    d = json.loads(raw.decode("utf8"))
    cps = lambda s: [ord(c) for c in s]  # noqa: E731
    up = lambda lst: [ord(u) if u else 0 for u in lst]  # noqa: E731
    data = [
        ("UA", cps(d["alphabets"]["ua"])), ("RU", cps(d["alphabets"]["ru"])), ("EN", cps(d["alphabets"]["en"])),
        ("UA_UPPER", up(d["upper"]["ua"])), ("RU_UPPER", up(d["upper"]["ru"])), ("EN_UPPER", up(d["upper"]["en"])),
        ("SHARED", cps(d["shared"])), ("NUMSET", cps(d["numset"])),
        ("LENGTHS_UA", d["modes"]["ua"]["lengths"]), ("LENGTHS_RU", d["modes"]["ru"]["lengths"]),
        ("LENGTHS_EN", d["modes"]["en"]["lengths"]), ("LENGTHS_NUM", d["modes"]["num"]["lengths"]),
    ]
    return hashlib.sha256(raw).hexdigest(), data


def lines_of(values, per=12, indent="    "):
    rows = []
    for i in range(0, len(values), per):
        rows.append(indent + ", ".join(str(v) for v in values[i:i + per]))
    return ",\n".join(rows)


def emit(lang):
    sha, data = load()
    out = []
    w = out.append
    if lang == "python":
        w("# %s" % NOTE)
        w("from __future__ import annotations\n")
        w('TABLES_SHA256 = "%s"\n' % sha)
        for name, v in data:
            w("%s = (\n%s,\n)\n" % (name, lines_of(v)))
    elif lang == "typescript":
        w("// %s" % NOTE)
        w('export const TABLES_SHA256 = "%s"\n' % sha)
        for name, v in data:
            w("export const %s: readonly number[] = [\n%s,\n]\n" % (name, lines_of(v)))
    elif lang == "csharp":
        w("// %s" % NOTE)
        w("namespace Packbin;\n")
        w("internal static class TextTables")
        w("{")
        w('    internal const string Sha256 = "%s";\n' % sha)
        for name, v in data:
            w("    internal static readonly int[] %s = new int[]\n    {\n%s,\n    };\n" % (name.title().replace("_", ""), lines_of(v, indent="        ")))
        w("}")
    elif lang == "java":
        w("// %s" % NOTE)
        w("package packbin;\n")
        w("final class TextTables {")
        w("    private TextTables() {}\n")
        w('    static final String SHA256 = "%s";\n' % sha)
        for name, v in data:
            w("    static final int[] %s = {\n%s,\n    };\n" % (name, lines_of(v, indent="        ")))
        w("}")
    elif lang == "rust":
        w("// %s" % NOTE)
        w('pub const TABLES_SHA256: &str = "%s";\n' % sha)
        for name, v in data:
            ty = "u8" if name.startswith("LENGTHS") else "u32"
            w("pub const %s: [%s; %d] = [\n%s,\n];\n" % (name, ty, len(v), lines_of(v)))
    elif lang == "go":
        w("// %s\n" % NOTE)
        w("package packbin\n")
        w('const textTablesSHA256 = "%s"\n' % sha)
        for name, v in data:
            ty = "uint8" if name.startswith("LENGTHS") else "rune"
            camel = "text" + "".join(p.title() for p in name.lower().split("_"))
            w("var %s = [%d]%s{\n%s,\n}\n" % (camel, len(v), ty, lines_of(v, indent="\t")))
    elif lang == "swift":
        w("// %s\n" % NOTE)
        w('let textTablesSHA256 = "%s"\n' % sha)
        for name, v in data:
            ty = "UInt8" if name.startswith("LENGTHS") else "UInt32"
            camel = "text" + "".join(p.title() for p in name.lower().split("_"))
            w("let %s: [%s] = [\n%s,\n]\n" % (camel, ty, lines_of(v)))
    elif lang == "cpp":
        w("// %s" % NOTE)
        w("#pragma once\n")
        w('#include "packbin/platform.hpp"\n')
        w("namespace packbin::text {\n")
        w('inline constexpr char kTablesSha256[] = "%s";\n' % sha)
        for name, v in data:
            ty = "std::uint8_t" if name.startswith("LENGTHS") else "std::uint32_t"
            camel = "k" + "".join(p.title() for p in name.lower().split("_"))
            w("inline constexpr %s %s[%d] = {\n%s,\n};\n" % (ty, camel, len(v), lines_of(v)))
        w("}  // namespace packbin::text")
    else:
        raise SystemExit("unknown language %s; one of %s" % (lang, " ".join(LANGS)))
    text = "\n".join(out) + "\n"
    if lang == "go":
        text = text.rstrip("\n") + "\n"  # gofmt rejects a trailing blank line, and CI runs gofmt -l
    return text


def main():
    if len(sys.argv) < 2 or sys.argv[1] not in LANGS:
        raise SystemExit(__doc__)
    text = emit(sys.argv[1])
    if len(sys.argv) >= 4 and sys.argv[2] == "--check":
        return 0 if open(sys.argv[3], encoding="utf8").read() == text else 1
    if len(sys.argv) == 3 and sys.argv[2] == "--path":
        print(SUGGESTED[sys.argv[1]])
        return 0
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
