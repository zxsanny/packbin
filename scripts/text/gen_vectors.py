#!/usr/bin/env python3
"""Write fixtures/text/vectors.txt with the reference codec (AZ-2647).

Usage: gen_vectors.py --corpus DIR [--out fixtures/text/vectors.txt]

DIR is the Tatoeba corpus directory of train_tables.py: some vectors are held-out sentences
(CC BY 2.0 FR, see fixtures/text/README.md). Everything else is built here. The output is
deterministic; `check-vectors.sh` re-derives every row from the contract.
"""
import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import textfmt as tf  # noqa: E402
import train_tables as tt  # noqa: E402

OUT_DEFAULT = os.path.join(HERE, "..", "..", "fixtures", "text", "vectors.txt")
HEADER = """# packbin compact text vectors (AZ-2647). Generated by scripts/text/gen_vectors.py, checked by check-vectors.sh.
# Rows are space separated; text is the hex of its UTF-8 bytes, "-" is the empty text.
#   enc  <id> <text> <field>          pack(text) is exactly <field>; unpack(<field>) is <text> and uses every byte
#   alt  <id> <text> <field>          unpack(<field>) is <text>; <field> is valid but not what the encoder writes
#   bad  <id> <kind> <buffer>         unpack of <buffer> as a string is refused; <kind> is the contract's refusal name
#   ref  <id> <packet>                the ring packet (type byte 01) with its strings in the new format
#   flip <id> <enc id>                flip each bit of that field's payload (not its count) in [field][5a]: the result is a
#                                     string or an error, and when it is a string the byte after it is 5a
# Sentences in "corpus" rows come from Tatoeba (https://tatoeba.org), CC BY 2.0 FR; authors are credited there.
"""


def h(text):
    return text.encode("utf8").hex() or "-"


def build_payload(tables, start, items, pad=None):
    """A payload from explicit symbols. items: ('s', mode, symbol) or ('raw', bytes). Returns the payload bytes."""
    bits = ""
    for it in items:
        if it[0] == "raw":
            bits += "".join(format(b, "08b") for b in it[1])
        else:
            _, mode, sym = it
            code, length = tables.codes[mode][tf.SYMBOL_INDEX[mode][sym]]
            bits += format(code, "0%db" % length)
    total = 6 + len(bits)
    size = (total + 7) // 8
    p = 8 * size - total if pad is None else pad
    stream = format(p, "03b") + format(start, "03b") + bits + "0" * (8 * size - total)
    return int(stream, 2).to_bytes(size, "big")


def field(payload):
    return tf.varint(len(payload)) + payload


def sym_l(mode, ch):
    return ("L", tf.ALPHA[mode].index(ch))


def sym_s(ch):
    return ("S", tf.SHARED.index(ch))


def sym_n(ch):
    return ("S", tf.NUMSET.index(ch))


def packet_user(tables, username, roles, access):
    def s(t):
        return tf.encode(t, tables)

    def lst(items):
        return len(items).to_bytes(2, "little") + b"".join(s(x) for x in items)
    keys = sorted(access, key=lambda k: k.encode("utf8"))
    out = b"\x01" + s(username) + lst(roles) + len(keys).to_bytes(2, "little")
    for k in keys:
        out += s(k) + lst(access[k])
    return out


def packet_nested(tables, access):
    def s(t):
        return tf.encode(t, tables)
    keys = sorted(access, key=lambda k: k.encode("utf8"))
    out = b"\x01" + len(keys).to_bytes(2, "little")
    for k in keys:
        rows = access[k]
        out += s(k) + len(rows).to_bytes(2, "little")
        for row in rows:
            rk = sorted(row, key=lambda x: x.encode("utf8"))
            out += len(rk).to_bytes(2, "little")
            for x in rk:
                out += s(x) + s(row[x])
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--corpus", default=os.environ.get("PACKBIN_TEXT_CORPUS"))
    ap.add_argument("--out", default=OUT_DEFAULT)
    args = ap.parse_args()
    if not args.corpus:
        raise SystemExit("--corpus DIR or PACKBIN_TEXT_CORPUS is required")
    T = tf.Tables.load()
    rows = []
    ids = set()

    def add(kind, rid, *cols):
        assert rid not in ids, rid
        ids.add(rid)
        rows.append(" ".join((kind, rid) + cols))

    def enc(rid, text):
        add("enc", rid, h(text), tf.encode(text, T).hex())

    # ---- hand cases
    hand = [
        ("empty", ""), ("one_a", "a"), ("one_ua", "я"), ("space", " "), ("apos_ua", "м'яч"), ("apos_en", "don't"),
        ("hello", "привіт"), ("hello_cap", "Привіт"), ("hello_caps", "ПРИВІТ, СВІТЕ!"), ("hello_world", "hello, world"),
        ("mixed_ok", "привіт ok 48.46"), ("mixed_long", "привіт! координати: 48.46, 35.04 ok?"), ("emoji", "привіт 😀"),
        ("lock_all", "ПРИВІТ"), ("lock_then_lower", "ПРИВІТ світ"), ("cap_each", "Іван Петренко з Києва"),
        ("ru_caps", "ПРИВЕТ, МИР"), ("ru_yo", "ёжик съел яблоко"), ("ru_text", "привет, как дела?"),
        ("en_caps", "HELLO WORLD"), ("en_title", "Hello World"), ("en_text", "the quick brown fox jumps over the lazy dog"),
        ("digits", "0123456789"), ("coords", "48.4612, 35.0403"), ("id", "id: 12345678"), ("time", "12:45"), ("minus", "-5.25"),
        ("ua_then_en", "слово word слово"), ("en_then_ua", "word слово word"), ("ua_ru", "привіт привет"),
        ("num_after_text", "рейс 2547"), ("text_after_num", "2547 рейс"), ("num_mid", "а 12 б"),
        ("newline", "рядок\nрядок"), ("tab", "a\tb"), ("nul", "a\x00b"), ("extras", ";()\"%/@+=*#&_$"),
        ("punct", "так, ні. - а: так! ні?"), ("bmp_apostrophe", "м’яч"), ("modifier_apostrophe", "мʼяч"),
        ("quotes_dash", "«цитата» — “slovo”"), ("polish", "zażółć gęślą jaźń"), ("german", "Größe"),
        ("accent", "é"), ("cjk", "中文"), ("zwj", "\U0001f468‍\U0001f469‍\U0001f467"),
        ("u10ffff", "\U0010ffff"), ("ud7ff", "퟿"), ("uffff", "￿"), ("ufeff", "﻿a"), ("rare_letters", "qqqqxxxxzzzz"),
        ("tr_dotted", "İstanbul"), ("sharp_s", "ß"), ("ukr_caps_all_letters", "".join(c.upper() for c in tf.UA if c != "'")),
        ("ukr_all_letters", tf.UA), ("rus_all_letters", tf.RU), ("eng_all_letters", tf.EN),
        ("shared_all", tf.SHARED), ("numset_all", tf.NUMSET), ("rus_caps_all_letters", "".join(c.upper() for c in tf.RU)),
        ("eng_caps_all_letters", "".join(c.upper() for c in tf.EN if c != "'")), ("apos_after_lock", "Н'Я"),
        ("lock_two_modes", "ПРИВІТ HELLO ПРИВЕТ"),
    ]
    for name, text in hand:
        enc("enc.hand." + name, text)
    # every ordered pair of modes: a letter or number of each, switched from each
    samples = {0: "ї", 1: "ы", 2: "x", 3: "7"}
    for a in range(4):
        for b in range(4):
            if a != b:
                enc("enc.switch.%s_%s" % (tf.MODE_NAMES[a], tf.MODE_NAMES[b]), samples[a] * 3 + " " + samples[b] * 3 + " " + samples[a] * 2)
    # payload size boundaries: raw q-runs and a compact text of 127 and 128 payload bytes
    enc("enc.size.raw_126", "q" * 126)
    enc("enc.size.raw_127", "q" * 127)
    enc("enc.size.raw_16382", "q" * 16382)
    enc("enc.size.raw_16383", "q" * 16383)
    base_text = "привіт світе, це довгий рядок для перевірки межі розміру. " * 12
    for target in (127, 128):
        for k in range(1, len(base_text)):
            cand = base_text[:k].rstrip()
            count, _ = tf.read_varint(tf.encode(cand, T), 0)
            if count == target:
                enc("enc.size.compact_%d" % target, cand)
                break
        else:
            raise SystemExit("no compact text with a %d-byte payload" % target)

    # ---- corpus rows (held-out sentences)
    rng = tt.Rng(tt.SEED)
    tests = {}
    for lang, key in (("ukr", "ua"), ("rus", "ru"), ("eng", "en")):
        _, tests[key] = tt.load_language(args.corpus, lang, rng)
    vrng = tt.Rng(tt.SEED + 1)
    low = {k: tt.lower_list(v) for k, v in tests.items()}
    n = 0
    for key, count_low, count_raw in (("ua", 40, 30), ("ru", 25, 20), ("en", 25, 20)):
        for t in tt.pick(vrng, low[key], count_low):
            n += 1
            enc("enc.corpus.%s_lower_%03d" % (key, n), t)
        for t in tt.pick(vrng, tests[key], count_raw):
            n += 1
            enc("enc.corpus.%s_raw_%03d" % (key, n), t)
    mixed = tt.mixed_messages(vrng, 25, low["ua"], low["ru"], low["en"])
    for i, t in enumerate(mixed):
        enc("enc.corpus.mixed_%03d" % i, t)
    for i, t in enumerate(tt.number_messages(vrng, 40, low["ua"])):
        enc("enc.numbers.%03d" % i, t)
    # random Unicode strings
    pool = [chr(c) for c in list(range(32, 127)) + list(range(0x410, 0x450)) + [0x401, 0x451, 0x404, 0x454, 0x406, 0x456, 0x407, 0x457,
                                                                               0x490, 0x491, 0x2014, 0x20ac, 0x1f600, 0x4e2d, 0xe9, 0x301, 0x2019, 10]]
    for i in range(40):
        t = "".join(vrng.choice(pool) for _ in range(vrng.below(60)))
        enc("enc.random.%03d" % i, t)

    # ---- alt rows: valid streams the encoder does not write
    def alt(rid, text, payload):
        f = field(payload)
        got, end = tf.decode(f, 0, T)
        assert got == text and end == len(f), rid
        assert tf.encode(text, T) != f, rid
        add("alt", rid, h(text), f.hex())

    alt("alt.escape_for_letter", "я", build_payload(T, 0, [("s", 0, ("ESC",)), ("raw", "я".encode())]))
    alt("alt.switch_pair", "а", build_payload(T, 0, [("s", 0, ("SW", 1)), ("s", 1, ("SW", 0)), ("s", 0, sym_l(0, "а"))]))
    alt("alt.lock_off_on", "я", build_payload(T, 0, [("s", 0, ("LOCK",)), ("s", 0, ("LOCK",)), ("s", 0, sym_l(0, "я"))]))
    alt("alt.lock_end", "я", build_payload(T, 0, [("s", 0, sym_l(0, "я")), ("s", 0, ("LOCK",))]))
    alt("alt.raw_mode_empty_text_escape", "\U0001f600", build_payload(T, 0, [("s", 0, ("ESC",)), ("raw", "\U0001f600".encode())]))
    alt("alt.start_in_other_mode", "я", build_payload(T, 3, [("s", 3, ("SW", 0)), ("s", 0, sym_l(0, "я"))]))
    alt("alt.number_for_digit", "5", build_payload(T, 0, [("s", 0, sym_s("5"))]))
    alt("alt.cap_letter_ru", "Я", build_payload(T, 1, [("s", 1, ("CAP",)), ("s", 1, sym_l(1, "я"))]))
    alt("alt.lock_over_switch", "ЯЫ", build_payload(T, 0, [("s", 0, ("LOCK",)), ("s", 0, sym_l(0, "я")), ("s", 0, ("SW", 1)), ("s", 1, sym_l(1, "ы"))]))
    alt("alt.raw_when_compact_is_smaller", "привіт", b"\x10" + "привіт".encode())

    # ---- bad rows
    def bad(rid, kind, buf):
        try:
            tf.decode(buf, 0, T)
        except tf.Refusal as e:
            assert e.kind == kind, (rid, e.kind, kind)
        else:
            raise AssertionError("not refused: " + rid)
        add("bad", rid, kind, buf.hex())

    bad("bad.varint_not_minimal", "varint", bytes.fromhex("8100"))
    bad("bad.varint_four_bytes", "varint", bytes.fromhex("80808001"))
    bad("bad.short_varint", "short", bytes.fromhex("80"))
    bad("bad.short_empty_buffer", "short", b"")
    bad("bad.short_payload", "short", bytes.fromhex("050102"))
    for m in (5, 6, 7):
        bad("bad.mode_%d" % m, "mode", bytes([1, m << 2]))
    bad("bad.raw_prefix", "raw", bytes.fromhex("021141"))
    bad("bad.raw_invalid_utf8", "utf8", bytes.fromhex("0310c328"))
    bad("bad.raw_bad_lead", "utf8", bytes.fromhex("0210ff"))
    bad("bad.pad_covers_prefix", "pad", bytes.fromhex("01e0"))
    good = tf.encode("привіт", T)
    nz = bytearray(good)
    nz[-1] |= 1
    bad("bad.pad_not_zero", "pad", bytes(nz))
    bad("bad.code_only_prefix", "code", bytes.fromhex("0100"))
    # a valid payload whose pad is raised until the stream ends inside a code
    base = bytearray(good)
    for extra in range(1, 8):
        trial = bytearray(good)
        pad = (trial[1] >> 5) + extra
        if pad > 7:
            break
        trial[1] = (trial[1] & 0x1F) | (pad << 5)
        try:
            tf.decode(bytes(trial), 0, T)
        except tf.Refusal as e:
            if e.kind == "code":
                bad("bad.code_cut", "code", bytes(trial))
                break
    else:
        pass
    ua_space = sym_s(" ")
    bad("bad.cap_then_space", "cap", field(build_payload(T, 0, [("s", 0, ("CAP",)), ("s", 0, ua_space)])))
    bad("bad.cap_at_end", "cap", field(build_payload(T, 0, [("s", 0, sym_l(0, "я")), ("s", 0, ("CAP",))])))
    bad("bad.cap_twice", "cap", field(build_payload(T, 0, [("s", 0, ("CAP",)), ("s", 0, ("CAP",)), ("s", 0, sym_l(0, "я"))])))
    bad("bad.cap_under_lock", "cap", field(build_payload(T, 0, [("s", 0, ("LOCK",)), ("s", 0, ("CAP",)), ("s", 0, sym_l(0, "я"))])))
    bad("bad.cap_then_switch", "cap", field(build_payload(T, 0, [("s", 0, ("CAP",)), ("s", 0, ("SW", 1)), ("s", 1, sym_l(1, "я"))])))
    bad("bad.cap_then_lock", "cap", field(build_payload(T, 0, [("s", 0, ("CAP",)), ("s", 0, ("LOCK",)), ("s", 0, sym_l(0, "я"))])))
    bad("bad.cap_then_apostrophe", "cap", field(build_payload(T, 0, [("s", 0, ("CAP",)), ("s", 0, sym_l(0, "'"))])))
    bad("bad.cap_then_esc", "cap", field(build_payload(T, 0, [("s", 0, ("CAP",)), ("s", 0, ("ESC",)), ("raw", b"a")])))
    esc = ("s", 0, ("ESC",))
    bad("bad.esc_cut_short", "esc", field(build_payload(T, 0, [esc, ("raw", b"\xf0")])))
    bad("bad.esc_no_bytes", "esc", field(build_payload(T, 0, [esc])))
    for name, raw in (("overlong", b"\xc0\x80"), ("surrogate", b"\xed\xa0\x80"), ("above_10ffff", b"\xf4\x90\x80\x80"),
                      ("stray_continuation", b"\x80"), ("bad_lead_ff", b"\xff"), ("bad_continuation", b"\xc3\x28"),
                      ("overlong3", b"\xe0\x80\x80")):
        bad("bad.esc_utf8_" + name, "utf8", field(build_payload(T, 0, [esc, ("raw", raw)])))
    spaces = field(build_payload(T, 0, [("s", 0, ua_space)] * 65536))
    bad("bad.length_65536", "length", spaces)

    # ---- ref rows
    ref = {
        "ref.user": packet_user(T, "zxsanny", ["user", "dispatcher"],
                                {"channel": ["read"], "map": ["read", "gps_fix", "set", "edit"], "store": ["read", "write"]}),
        "ref.nested": packet_nested(T, {"map": [{"op": "gps_fix"}], "store": [{"op": "read"}, {"op": "write"}]}),
        "ref.user_ua": packet_user(T, "Олександр", ["диспетчер", "Оператор"], {"карта": ["читати", "правити"], "канал": ["читати"]}),
        "ref.nested_mixed": packet_nested(T, {"Карта": [{"op": "gps_fix", "note": "увага 48.46, 35.04"}], "store": [{"op": "ЧИТАТИ"}]}),
    }
    for rid, pkt in ref.items():
        add("ref", rid, pkt.hex())

    # ---- flip rows: a spread of enc rows
    enc_ids = [r.split(" ")[1] for r in rows if r.startswith("enc ")]
    chosen = [i for i in enc_ids if i.startswith("enc.hand.") or i.startswith("enc.size.compact")]
    chosen += [i for i in enc_ids if i.startswith("enc.numbers.")][:3]
    chosen = [i for i in chosen if i not in ("enc.hand.empty",) and "raw_16" not in i]
    for i in chosen[:26]:
        add("flip", "flip." + i[4:], i)
    with open(args.out, "w", encoding="utf8", newline="\n") as f:
        f.write(HEADER + "\n".join(rows) + "\n")
    kinds = {}
    for r in rows:
        kinds[r.split(" ")[0]] = kinds.get(r.split(" ")[0], 0) + 1
    print("wrote %d rows: %s" % (len(rows), kinds))
    return 0


if __name__ == "__main__":
    sys.exit(main())
